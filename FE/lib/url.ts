/**
 * 링크로 그려도 되는 URL인지. `javascript:`·`data:` 같은 스킴을 막아 클릭 시 스크립트 실행을 차단한다.
 *
 * BE가 저장을 막더라도 화면에서 한 번 더 본다 — 규칙이 생기기 전에 들어온 값이 DB에 남아 있고,
 * "서버가 걸러 줬겠지"라고 믿는 순간 다음 소비처에서 같은 구멍이 열린다.
 * (증빙 링크에만 있던 가드를 공용으로 올렸다. 티켓 링크에는 빠져 있었다 — 2026-09-09)
 */
export function isHttpUrl(u: string): boolean {
  return /^https?:\/\//i.test(u.trim());
}
